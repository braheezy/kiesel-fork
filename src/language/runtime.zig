/// 15.7.10 Runtime Semantics: ClassFieldDefinitionEvaluation
/// https://tc39.es/ecma262/#sec-runtime-semantics-classfielddefinitionevaluation
fn classFieldDefinitionEvaluation(
    agent: *Agent,
    field_definition: ast.FieldDefinition,
    home_obj: *Object,
    pre_evaluated_name: Value,
) Agent.Error!ClassFieldDefinition {
    const realm = agent.currentRealm();

    // 1. Let name be ? Evaluation of ClassElementName.
    const name: PropertyKeyOrPrivateName = blk: {
        if (pre_evaluated_name.toPrivateName()) |private_name| {
            break :blk .{ .private_name = private_name };
        }
        const property_key = try pre_evaluated_name.toPropertyKey(agent);
        break :blk .{ .property_key = property_key };
    };

    // 2. If Initializer is present, then
    const initializer = if (field_definition.initializer) |initializer| blk: {
        // a. Let formalParamList be an instance of the production FormalParameters : [empty] .
        const formal_param_list: ast.FormalParameters = .{
            .items = &.{},
            .arguments_object_needed = false,
        };

        // b. Let envRecord be the LexicalEnvironment of the running execution context.
        const env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

        // c. Let privateEnv be the running execution context's PrivateEnvironment.
        const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

        // d. Let sourceText be the empty sequence of Unicode code points.
        const source_text: SourceText = .{ .string = .empty };

        // e. Let initializer be OrdinaryFunctionCreate(%Function.prototype%, sourceText,
        //    formalParamList, Initializer, non-lexical-this, envRecord, privateEnv).
        const body: ast.FunctionBody = blk_body: {
            const statement = try agent.gc_allocator.create(ast.Statement);
            statement.* = .{ .return_statement = .{ .expression = initializer } };
            const items = try agent.gc_allocator.alloc(ast.StatementListItem, 1);
            items[0] = .{ .statement = statement };
            const statement_list: ast.StatementList = .{ .items = items };
            break :blk_body .{
                .type = .normal,
                .statement_list = statement_list,
                .strict = true,
                .arguments_object_needed = false,
            };
        };
        const initializer_function = try ordinaryFunctionCreate(
            agent,
            try realm.intrinsic(.function_prototype),
            source_text,
            formal_param_list,
            body,
            .non_lexical_this,
            env,
            private_env,
        );

        // f. Perform MakeMethod(initializer, homeObj).
        makeMethod(initializer_function, home_obj);

        // g. Set initializer.[[ClassFieldInitializerName]] to name.
        const class_data = try initializer_function.fields.ensureClassData(agent);
        class_data.class_field_initializer_name = name;

        // NOTE: The spec does not set a function name but we rely on it for IR/bytecode metadata.
        try setFunctionName(agent, &initializer_function.object, name, null);

        break :blk initializer_function;
    } else blk: {
        // 3. Else,
        // a. Let initializer be empty.
        break :blk null;
    };

    // 4. Return the ClassFieldDefinition Record { [[Name]]: name, [[Initializer]]: initializer }.
    return .{ .name = name, .initializer = initializer };
}

/// 15.7.11 Runtime Semantics: ClassStaticBlockDefinitionEvaluation
/// https://tc39.es/ecma262/#sec-runtime-semantics-classstaticblockdefinitionevaluation
fn classStaticBlockDefinitionEvaluation(
    agent: *Agent,
    class_static_block: ast.ClassStaticBlock,
    home_obj: *Object,
) std.mem.Allocator.Error!ClassStaticBlockDefinition {
    const realm = agent.currentRealm();

    // 1. Let lexicalEnv be the running execution context's LexicalEnvironment.
    const lexical_env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

    // 2. Let privateEnv be the running execution context's PrivateEnvironment.
    const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

    // 3. Let sourceText be the empty sequence of Unicode code points.
    const source_text: SourceText = .{ .string = .empty };

    // 4. Let formalParams be an instance of the production FormalParameters : [empty] .
    const formal_parameter_list: ast.FormalParameters = .{
        .items = &.{},
        .arguments_object_needed = false,
    };

    // 5. Let bodyFunc be OrdinaryFunctionCreate(%Function.prototype%, sourceText, formalParams,
    //    ClassStaticBlockBody, non-lexical-this, lexicalEnv, privateEnv).
    const body: ast.FunctionBody = blk_body: {
        // NOTE: This serves as a replacement for EvaluateClassStaticBlockBody, which invokes
        //       FunctionDeclarationInstantiation before evaluating the statement list.
        break :blk_body .{
            .type = .normal,
            .statement_list = class_static_block.statement_list,
            .strict = true,
            .arguments_object_needed = false,
        };
    };
    const body_func = try ordinaryFunctionCreate(
        agent,
        try realm.intrinsic(.function_prototype),
        source_text,
        formal_parameter_list,
        body,
        .non_lexical_this,
        lexical_env,
        private_env,
    );

    // 6. Perform MakeMethod(bodyFunc, homeObj).
    makeMethod(body_func, home_obj);

    // NOTE: The spec does not set a function name but we rely on it for IR/bytecode metadata.
    try setFunctionName(agent, &body_func.object, PropertyKey.from(""), null);

    // 7. Return the ClassStaticBlockDefinition Record { [[BodyFunction]]: bodyFunc }.
    return .{ .body_function = body_func };
}

/// 15.7.13 Runtime Semantics: ClassElementEvaluation
/// https://tc39.es/ecma262/#sec-static-semantics-classelementevaluation
fn classElementEvaluation(
    agent: *Agent,
    class_element: ast.ClassElement,
    obj: *Object,
    pre_evaluated_name: Value,
    source: []const u8,
) Agent.Error!?union(enum) {
    class_field_definition: ClassFieldDefinition,
    class_static_block_definition: ClassStaticBlockDefinition,
    private_method_definition: PrivateMethodDefinition,
} {
    switch (class_element) {
        // ClassElement :
        //     FieldDefinition ;
        //     static FieldDefinition ;
        .field_definition,
        .static_field_definition,
        => |field_definition| {
            // 1. Return ? ClassFieldDefinitionEvaluation of FieldDefinition with argument obj.
            return .{
                .class_field_definition = try classFieldDefinitionEvaluation(
                    agent,
                    field_definition,
                    obj,
                    pre_evaluated_name,
                ),
            };
        },

        // ClassElement :
        //     MethodDefinition
        //     static MethodDefinition
        .method_definition,
        .static_method_definition,
        => |method_definition| {
            // 1. Return ? MethodDefinitionEvaluation of MethodDefinition with arguments obj and
            //    false.
            if (try methodDefinitionEvaluation(
                agent,
                .{ .property_name = pre_evaluated_name, .method = method_definition.method },
                obj,
                false,
                source,
            )) |private_method_definition|
                return .{ .private_method_definition = private_method_definition }
            else
                return null;
        },

        // ClassElement : ClassStaticBlock
        .class_static_block => |class_static_block| {
            // 1. Return the ClassStaticBlockDefinitionEvaluation of ClassStaticBlock with argument
            //    obj.
            return .{
                .class_static_block_definition = try classStaticBlockDefinitionEvaluation(
                    agent,
                    class_static_block,
                    obj,
                ),
            };
        },

        // ClassElement : ;
        .empty_statement => {
            // 1. Return empty.
            return null;
        },
    }
}

/// 15.7.14 Runtime Semantics: ClassDefinitionEvaluation
/// https://tc39.es/ecma262/#sec-runtime-semantics-classdefinitionevaluation
pub fn classDefinitionEvaluation(
    agent: *Agent,
    class_tail: ast.ClassTail,
    class_binding: ?*const String,
    class_name: *const String,
    source_range: ast.SourceRange,
    source: []const u8,
    pre_evaluated_heritage: ?Value,
    pre_evaluated_element_names: []const Value,
) Agent.Error!*Object {
    const realm = agent.currentRealm();

    // 1. Let envRecord be the LexicalEnvironment of the running execution context.
    const env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

    // 2. Let classEnv be NewDeclarativeEnvironment(envRecord).
    const class_env = try newDeclarativeEnvironment(agent.gc_allocator, env);

    // 3. If classBinding is not undefined, then
    if (class_binding != null) {
        // a. Perform ! classEnv.CreateImmutableBinding(classBinding, true).
        class_env.createImmutableBinding(
            agent,
            class_binding.?,
            true,
        ) catch |err| try noexcept(err);
    }

    // 4. Let outerPrivateEnv be the running execution context's PrivateEnvironment.
    // 5. Let classPrivateEnv be NewPrivateEnvironment(outerPrivateEnv).
    const class_private_env = agent.runningExecutionContext().ecmascript_code.private_environment.?;

    // 6. If ClassBody is present, then
    //     a. For each String description of the PrivateBoundIdentifiers of ClassBody, do
    //         i. If classPrivateEnv.[[Names]] contains a Private Name privateName such that
    //            privateName.[[Description]] is description, then
    //             1. Assert: This is only possible for getter/setter pairs.
    //         ii. Else,
    //             1. Let name be a new Private Name whose [[Description]] is description.
    //             2. Append name to classPrivateEnv.[[Names]].
    // NOTE: This is handled via the generated bytecode.

    var proto_parent: ?*Object = undefined;
    var ctor_parent: *Object = undefined;

    // 7. If ClassHeritage is not present, then
    if (class_tail.class_heritage == null) {
        // a. Let protoParent be %Object.prototype%.
        proto_parent = try realm.intrinsic(.object_prototype);

        // b. Let ctorParent be %Function.prototype%.
        ctor_parent = try realm.intrinsic(.function_prototype);
    } else {
        // 8. Else,
        // a. Set the running execution context's LexicalEnvironment to classEnv.
        agent.runningExecutionContext().ecmascript_code.lexical_environment = .{ .declarative_environment = class_env };

        // b. NOTE: The running execution context's PrivateEnvironment is outerPrivateEnv when
        //    evaluating ClassHeritage.
        // c. Let superclassRef be Completion(Evaluation of ClassHeritage).
        const superclass = pre_evaluated_heritage.?;

        // d. Set the running execution context's LexicalEnvironment to envRecord.
        agent.runningExecutionContext().ecmascript_code.lexical_environment = env;

        // e. Let superclass be ? GetValue(? superclassRef).

        // f. If superclass is null, then
        if (superclass.isNull()) {
            // i. Let protoParent be null.
            proto_parent = null;

            // ii. Let ctorParent be %Function.prototype%.
            ctor_parent = try realm.intrinsic(.function_prototype);
        }
        // g. Else if IsConstructor(superclass) is false, then
        else if (!superclass.isConstructor()) {
            // i. Throw a TypeError exception.
            return agent.throwException(.type_error, "{f} is not a constructor", .{superclass});
        } else {
            // h. Else,
            // i. Let protoParent be ? Get(superclass, "prototype").
            const proto_parent_value = try superclass.asObject().get(agent, PropertyKey.from("prototype"));

            // ii. If protoParent is not an Object and protoParent is not null, throw a TypeError
            //     exception.
            if (!proto_parent_value.isObject() and !proto_parent_value.isNull()) {
                return agent.throwException(
                    .type_error,
                    "{f} is not an Object or null",
                    .{proto_parent_value},
                );
            }

            proto_parent = if (proto_parent_value.isObject())
                proto_parent_value.asObject()
            else
                null;

            // iii. Let ctorParent be superclass.
            ctor_parent = superclass.asObject();
        }
    }

    // 9. Let proto be OrdinaryObjectCreate(protoParent).
    const proto = try ordinaryObjectCreate(agent, proto_parent);

    // 10. If ClassBody is not present, let ctor be empty.
    // 11. Else, let ctor be the ConstructorMethod of ClassBody.
    const ctor = class_tail.class_body.constructorMethod();

    // 12. Set the running execution context's LexicalEnvironment to classEnv.
    agent.runningExecutionContext().ecmascript_code.lexical_environment = .{ .declarative_environment = class_env };

    // 13. Set the running execution context's PrivateEnvironment to classPrivateEnv.
    agent.runningExecutionContext().ecmascript_code.private_environment = class_private_env;

    // 14. If ctor is empty, then
    var ctor_func = if (ctor == null) blk: {
        // a. Let defaultCtor be a new Abstract Closure with no parameters that captures nothing and
        //    performs the following steps when called:
        const default_constructor = struct {
            fn func(agent_: *Agent, arguments: Arguments, new_target: ?*Object) Agent.Error!Value {
                // i. Let args be the List of arguments that was passed to this function by [[Call]]
                //    or [[Construct]].
                const args = arguments.values;

                // ii. If NewTarget is undefined, throw a TypeError exception.
                if (new_target == null) {
                    return agent_.throwException(.type_error, "Class must be constructed with 'new'", .{});
                }

                // iii. Let ctorFunc be the active function object.
                const ctor_func = agent_.activeFunctionObject();
                const class_constructor_fields = ctor_func.as(builtins.BuiltinFunction).fields.additionalFieldsAs(ClassConstructorFields);

                // iv. If ctorFunc.[[ConstructorKind]] is derived, then
                var result = if (class_constructor_fields.constructor_kind == .derived) blk: {
                    // 1. NOTE: This branch behaves similarly to
                    //    `constructor(...args) { super(...args); }`. The most notable distinction
                    //    is that while the aforementioned ECMAScript source text observably calls
                    //    the %Symbol.iterator% method on `%Array.prototype%`, this function does
                    //    not.

                    // 2. Let func be ! ctorFunc.[[GetPrototypeOf]]().
                    const proto_func = ctor_func.internalMethods().getPrototypeOf(
                        agent_,
                        ctor_func,
                    ) catch |err| try noexcept(err);

                    // 3. If IsConstructor(func) is false, throw a TypeError exception.
                    if (proto_func == null or !Value.from(proto_func.?).isConstructor()) {
                        return agent_.throwException(
                            .type_error,
                            "{f} is not a constructor",
                            .{
                                if (proto_func == null)
                                    Value.undefined
                                else
                                    Value.from(proto_func.?),
                            },
                        );
                    }

                    // 4. Let result be ? Construct(func, args, NewTarget).
                    break :blk try proto_func.?.construct(agent_, args, new_target.?);
                } else blk: {
                    // v. Else,
                    // 1. NOTE: This branch behaves similarly to `constructor() {}`.
                    // 2. Let result be ? OrdinaryCreateFromConstructor(NewTarget,
                    //    "%Object.prototype%").
                    const result = try ordinaryCreateFromConstructor(
                        builtins.Object,
                        agent_,
                        new_target.?,
                        .object_prototype,
                        {},
                    );
                    break :blk &result.object;
                };

                // vi. Perform ? InitializeInstanceElements(result, ctorFunc).
                try result.initializeInstanceElements(agent_, ctor_func);

                // vii. Return NormalCompletion(result).
                return Value.from(result);
            }
        }.func;

        // b. Let ctorFunc be CreateBuiltinFunction(defaultCtor, 0, className,
        //    « [[ConstructorKind]], [[SourceText]], [[PrivateMethods]], [[Fields]] », the current
        //    Realm Record, ctorParent).
        const class_constructor_fields = try agent.gc_allocator.create(ClassConstructorFields);
        const ctor_func = try createBuiltinFunction(
            agent,
            .{ .constructor = default_constructor },
            0,
            null,
            .{
                .realm = agent.currentRealm(),
                .proto = ctor_parent,
                .flags = .{ .async = false, .is_class_constructor = true },
                .additional_fields = class_constructor_fields,
            },
        );
        try setFunctionName(agent, &ctor_func.object, PropertyKey.from(class_name), null);
        break :blk &ctor_func.object;
    } else blk: {
        // 15. Else,
        // a. Let ctorInfo be ! DefineMethod of ctor with arguments proto and ctorParent.
        const ctor_info = defineMethod(
            agent,
            ctor.?.method.method,
            Value.from("constructor"),
            proto,
            ctor_parent,
            source,
        ) catch |err| try noexcept(err);

        // b. Let ctorFunc be ctorInfo.[[Closure]].
        const ctor_func = ctor_info.closure;

        // c. Perform MakeClassConstructor(ctorFunc).
        makeClassConstructor(ctor_func);

        // d. Perform SetFunctionName(ctorFunc, className).
        try setFunctionName(agent, &ctor_func.object, PropertyKey.from(class_name), null);

        break :blk &ctor_func.object;
    };

    // 16. Set ctorFunc.[[SourceText]] to sourceText.
    const source_text: SourceText = .{ .slice = .{
        .source = source,
        .source_range = source_range,
    } };
    if (ctor_func.cast(builtins.ECMAScriptFunction)) |ecmascript_function| {
        ecmascript_function.fields.source_text = source_text;
    } else if (ctor_func.cast(builtins.BuiltinFunction)) |builtin_function| {
        const class_constructor_fields = builtin_function.fields.additionalFieldsAs(ClassConstructorFields);
        class_constructor_fields.source_text = source_text;
    } else unreachable;

    // 17. Perform MakeConstructor(ctorFunc, false, proto).
    try makeConstructor(agent, ctor_func, .{ .writable_proto = false, .proto = proto });

    // 18. If ClassHeritage is present, set ctorFunc.[[ConstructorKind]] to derived.
    if (class_tail.class_heritage != null) {
        if (ctor_func.cast(builtins.ECMAScriptFunction)) |ecmascript_function| {
            ecmascript_function.fields.flags.constructor_kind = .derived;
        } else if (ctor_func.cast(builtins.BuiltinFunction)) |builtin_function| {
            const class_constructor_fields = builtin_function.fields.additionalFieldsAs(ClassConstructorFields);
            class_constructor_fields.constructor_kind = .derived;
        } else unreachable;
    }

    // 19. Perform ! DefineMethodProperty(proto, "constructor", ctorFunc, false).
    _ = defineMethodProperty(
        agent,
        proto,
        .{ .property_key = PropertyKey.from("constructor") },
        ctor_func,
        false,
    ) catch |err| try noexcept(err);

    // 20. If ClassBody is not present, let classElements be a new empty List.
    // 21. Else, let classElements be the NonConstructorElements of ClassBody.
    const class_elements = try class_tail.class_body.nonConstructorElements(agent.gc_allocator);
    defer agent.gc_allocator.free(class_elements);

    // 22. Let instancePrivateMethods be a new empty List.
    var instance_private_methods: std.ArrayList(PrivateMethodDefinition) = .empty;
    // Converted to owned slice, no `deinit()` needed

    // 23. Let staticPrivateMethods be a new empty List.
    var static_private_methods: std.ArrayList(PrivateMethodDefinition) = .empty;
    defer static_private_methods.deinit(agent.gc_allocator);

    // 24. Let instanceFields be a new empty List.
    var instance_fields: std.ArrayList(ClassFieldDefinition) = .empty;
    // Converted to owned slice, no `deinit()` needed

    // 25. Let staticElements be a new empty List.
    var static_elements: std.ArrayList(union(enum) {
        class_field_definition: ClassFieldDefinition,
        class_static_block_definition: ClassStaticBlockDefinition,
    }) = .empty;
    defer static_elements.deinit(agent.gc_allocator);

    // 26. For each ClassElement classElement of classElements, do
    for (class_elements, pre_evaluated_element_names) |class_element, pre_evaluated_name| {
        // a. If IsStatic of classElement is false, then
        const element_or_error = if (!class_element.isStatic()) blk: {
            // i. Let element be Completion(ClassElementEvaluation of classElement with argument
            //    proto).
            break :blk classElementEvaluation(agent, class_element, proto, pre_evaluated_name, source);
        } else blk: {
            // b. Else,
            // i. Let element be Completion(ClassElementEvaluation of classElement with argument
            //    ctorFunc).
            break :blk classElementEvaluation(agent, class_element, ctor_func, pre_evaluated_name, source);
        };

        // c. If element is an abrupt completion, then
        // d. Set element to ! element.
        const maybe_element = element_or_error catch |err| {
            // i. Set the running execution context's LexicalEnvironment to envRecord.
            agent.runningExecutionContext().ecmascript_code.lexical_environment = env;

            // ii. Set the running execution context's PrivateEnvironment to outerPrivateEnv.
            // NOTE: This is handled via the generated bytecode.

            // iii. Return ? element.
            return err;
        };

        if (maybe_element) |element| switch (element) {
            // e. If element is a PrivateElement, then
            .private_method_definition => |private_method_definition| {
                // i. Assert: element.[[Kind]] is either method or accessor.
                std.debug.assert(
                    private_method_definition.private_element == .method or
                        private_method_definition.private_element == .accessor,
                );

                // ii. If IsStatic of classElement is false, let container be
                //     instancePrivateMethods.
                // iii. Else, let container be staticPrivateMethods.
                const container = if (!class_element.isStatic())
                    &instance_private_methods
                else
                    &static_private_methods;

                // iv. If container contains a PrivateElement existingElement such that
                //     existingElement.[[Key]] is element.[[Key]], then
                if (for (container.items, 0..) |p, index| {
                    if (p.private_name.eql(private_method_definition.private_name)) {
                        break .{ .private_element = p.private_element, .index = index };
                    }
                } else null) |found| {
                    // 1. Assert: element.[[Kind]] and existingElement.[[Kind]] are both accessor.
                    std.debug.assert(
                        private_method_definition.private_element == .accessor and
                            found.private_element == .accessor,
                    );

                    var combined = private_method_definition;

                    // 2. If element.[[Getter]] is undefined, then
                    if (private_method_definition.private_element.accessor.getter == null) {
                        // a. Let combined be PrivateElement { [[Key]]: element.[[Key]],
                        //    [[Kind]]: accessor, [[Getter]]: existingElement.[[Getter]],
                        //    [[Setter]]: element.[[Setter]] }.
                        combined.private_element.accessor.getter = found.private_element.accessor.getter;
                    } else {
                        // 3. Else,
                        // a. Let combined be PrivateElement { [[Key]]: element.[[Key]],
                        //    [[Kind]]: accessor, [[Getter]]: element.[[Getter]],
                        //    [[Setter]]: existingElement.[[Setter]] }.
                        combined.private_element.accessor.setter = found.private_element.accessor.setter;
                    }

                    // 4. Replace existingElement in container with combined.
                    container.items[found.index] = combined;
                } else {
                    // v. Else,
                    // 1. Append element to container.
                    try container.append(agent.gc_allocator, private_method_definition);
                }
            },

            // f. Else if element is a ClassFieldDefinition Record, then
            .class_field_definition => |class_field_definition| {
                // i. If IsStatic of classElement is false, append element to instanceFields.
                // ii. Else, append element to staticElements.
                if (!class_element.isStatic())
                    try instance_fields.append(agent.gc_allocator, class_field_definition)
                else
                    try static_elements.append(
                        agent.gc_allocator,
                        .{ .class_field_definition = class_field_definition },
                    );
            },

            // g. Else if element is a ClassStaticBlockDefinition Record, then
            .class_static_block_definition => |class_static_block_definition| {
                // i. Append element to staticElements.
                try static_elements.append(
                    agent.gc_allocator,
                    .{ .class_static_block_definition = class_static_block_definition },
                );
            },
        } else {
            // h. Else,
            // i. Assert: element is empty.
        }
    }

    // 27. Set the running execution context's LexicalEnvironment to envRecord.
    agent.runningExecutionContext().ecmascript_code.lexical_environment = env;

    // 28. If classBinding is not undefined, then
    if (class_binding != null) {
        // a. Perform ! classEnv.InitializeBinding(classBinding, ctorFunc).
        class_env.initializeBinding(class_binding.?, Value.from(ctor_func));
    }

    // 29. Set ctorFunc.[[PrivateMethods]] to instancePrivateMethods.
    // 30. Set ctorFunc.[[Fields]] to instanceFields.
    if (ctor_func.cast(builtins.ECMAScriptFunction)) |ecmascript_function| {
        if (instance_private_methods.items.len != 0 or
            instance_fields.items.len != 0 or
            ecmascript_function.fields.class_data != null)
        {
            const class_data = try ecmascript_function.fields.ensureClassData(agent);
            class_data.private_methods = try instance_private_methods.toOwnedSlice(agent.gc_allocator);
            class_data.fields = try instance_fields.toOwnedSlice(agent.gc_allocator);
        }
    } else if (ctor_func.cast(builtins.BuiltinFunction)) |builtin_function| {
        const class_constructor_fields = builtin_function.fields.additionalFieldsAs(ClassConstructorFields);
        class_constructor_fields.private_methods = try instance_private_methods.toOwnedSlice(agent.gc_allocator);
        class_constructor_fields.fields = try instance_fields.toOwnedSlice(agent.gc_allocator);
    } else unreachable;

    // 31. For each PrivateElement method of staticPrivateMethods, do
    for (static_private_methods.items) |method| {
        // a. Perform ! PrivateMethodOrAccessorAdd(ctorFunc, method).
        ctor_func.privateMethodOrAccessorAdd(
            agent,
            method.private_name,
            method.private_element,
        ) catch |err| try noexcept(err);
    }

    // 32. For each element elementRecord of staticElements, do
    for (static_elements.items) |element| {
        const result = switch (element) {
            // a. If elementRecord is a ClassFieldDefinition Record, then
            .class_field_definition => |class_field_definition| blk: {
                // i. Let result be Completion(DefineField(ctorFunc, elementRecord)).
                break :blk ctor_func.defineField(agent, class_field_definition);
            },
            // b. Else,
            .class_static_block_definition => |class_static_block_definition| blk: {
                // i. Assert: elementRecord is a ClassStaticBlockDefinition Record.
                // ii. Let result be Completion(Call(elementRecord.[[BodyFunction]], ctorFunc)).
                const body_function = &class_static_block_definition.body_function.object;
                _ = body_function.call(
                    agent,
                    Value.from(ctor_func),
                    &.{},
                ) catch |err| break :blk err;
            },
        };

        // c. If result is an abrupt completion, then
        _ = result catch |err| {
            // i. Set the running execution context's PrivateEnvironment to outerPrivateEnv.
            // NOTE: This is handled via the generated bytecode.

            // ii. Return ? result.
            return err;
        };
    }

    // 33. Set the running execution context's PrivateEnvironment to outerPrivateEnv.
    // NOTE: This is handled via the generated bytecode.

    // 34. Return ctorFunc.
    return ctor_func;
}

/// 15.8.2 Runtime Semantics: InstantiateAsyncFunctionObject
/// https://tc39.es/ecma262/#sec-runtime-semantics-instantiateasyncfunctionobject
pub fn instantiateAsyncFunctionObject(
    agent: *Agent,
    async_function_declaration: ast.AsyncFunctionDeclaration,
    env: Environment,
    private_env: ?*PrivateEnvironment,
    source: []const u8,
) std.mem.Allocator.Error!*builtins.ECMAScriptFunction {
    const realm = agent.currentRealm();

    // AsyncFunctionDeclaration : async function BindingIdentifier ( FormalParameters ) { AsyncFunctionBody }
    if (async_function_declaration.identifier) |identifier| {
        // 1. Let name be the StringValue of BindingIdentifier.
        const name = try String.fromUtf8(agent, identifier);

        // 2. Let sourceText be the source text matched by AsyncFunctionDeclaration.
        const source_text: SourceText = .{ .slice = .{
            .source = source,
            .source_range = async_function_declaration.source_range,
        } };

        // 3. Let closure be OrdinaryFunctionCreate(%AsyncFunction.prototype%, sourceText,
        //    FormalParameters, AsyncFunctionBody, non-lexical-this, envRecord, privateEnv).
        const closure = try ordinaryFunctionCreate(
            agent,
            try realm.intrinsic(.async_function_prototype),
            source_text,
            async_function_declaration.formal_parameters,
            async_function_declaration.function_body,
            .non_lexical_this,
            env,
            private_env,
        );

        // 4. Perform SetFunctionName(closure, name).
        try setFunctionName(agent, &closure.object, PropertyKey.from(name), null);

        // 5. Return closure.
        return closure;
    }
    // AsyncFunctionDeclaration : async function ( FormalParameters ) { AsyncFunctionBody }
    else {
        // 1. Let sourceText be the source text matched by AsyncFunctionDeclaration.
        const source_text: SourceText = .{ .slice = .{
            .source = source,
            .source_range = async_function_declaration.source_range,
        } };

        // 2. Let closure be OrdinaryFunctionCreate(%AsyncFunction.prototype%, sourceText,
        //    FormalParameters, AsyncFunctionBody, non-lexical-this, envRecord, privateEnv).
        const closure = try ordinaryFunctionCreate(
            agent,
            try realm.intrinsic(.async_function_prototype),
            source_text,
            async_function_declaration.formal_parameters,
            async_function_declaration.function_body,
            .non_lexical_this,
            env,
            private_env,
        );

        // 3. Perform SetFunctionName(closure, "default").
        try setFunctionName(agent, &closure.object, PropertyKey.from("default"), null);

        // 4. Return closure.
        return closure;
    }
}

/// 15.8.3 Runtime Semantics: InstantiateAsyncFunctionExpression
/// https://tc39.es/ecma262/#sec-runtime-semantics-instantiateasyncfunctionexpression
pub fn instantiateAsyncFunctionExpression(
    agent: *Agent,
    async_function_expression: ast.AsyncFunctionExpression,
    default_name: ?[]const u8,
    source: []const u8,
) std.mem.Allocator.Error!*builtins.ECMAScriptFunction {
    const realm = agent.currentRealm();

    // AsyncFunctionExpression : async function BindingIdentifier ( FormalParameters ) { AsyncFunctionBody }
    if (async_function_expression.identifier) |identifier| {
        // 1. Assert: name is not present.
        std.debug.assert(default_name == null);

        // 2. Set name to the StringValue of BindingIdentifier.
        const name = try String.fromUtf8(agent, identifier);

        // 3. Let outerEnv be the LexicalEnvironment of the running execution context.
        const outer_env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

        // 4. Let funcEnv be NewDeclarativeEnvironment(outerEnv).
        const func_env = try newDeclarativeEnvironment(agent.gc_allocator, outer_env);

        // 5. Perform ! funcEnv.CreateImmutableBinding(name, false).
        func_env.createImmutableBinding(agent, name, false) catch |err| try noexcept(err);

        // 6. Let privateEnv be the running execution context's PrivateEnvironment.
        const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

        // 7. Let sourceText be the source text matched by AsyncFunctionExpression.
        const source_text: SourceText = .{ .slice = .{
            .source = source,
            .source_range = async_function_expression.source_range,
        } };

        // 8. Let closure be OrdinaryFunctionCreate(%AsyncFunction.prototype%, sourceText,
        //    FormalParameters, AsyncFunctionBody, non-lexical-this, funcEnv, privateEnv).
        const closure = try ordinaryFunctionCreate(
            agent,
            try realm.intrinsic(.async_function_prototype),
            source_text,
            async_function_expression.formal_parameters,
            async_function_expression.function_body,
            .non_lexical_this,
            .{ .declarative_environment = func_env },
            private_env,
        );

        // 9. Perform SetFunctionName(closure, name).
        try setFunctionName(agent, &closure.object, PropertyKey.from(name), null);

        // 10. Perform ! funcEnv.InitializeBinding(name, closure).
        func_env.initializeBinding(name, Value.from(&closure.object));

        // 11. Return closure.
        return closure;
    }
    // AsyncFunctionExpression : async function ( FormalParameters ) { AsyncFunctionBody }
    else {
        // 1. If name is not present, set name to the empty String.
        const name: *const String = if (default_name) |name|
            try String.fromUtf8(agent, name)
        else
            .empty;

        // 2. Let envRecord be the LexicalEnvironment of the running execution context.
        const env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

        // 3. Let privateEnv be the running execution context's PrivateEnvironment.
        const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

        // 4. Let sourceText be the source text matched by AsyncFunctionExpression.
        const source_text: SourceText = .{ .slice = .{
            .source = source,
            .source_range = async_function_expression.source_range,
        } };

        // 5. Let closure be OrdinaryFunctionCreate(%AsyncFunction.prototype%, sourceText,
        //    FormalParameters, AsyncFunctionBody, non-lexical-this, envRecord, privateEnv).
        const closure = try ordinaryFunctionCreate(
            agent,
            try realm.intrinsic(.async_function_prototype),
            source_text,
            async_function_expression.formal_parameters,
            async_function_expression.function_body,
            .non_lexical_this,
            env,
            private_env,
        );

        // 6. Perform SetFunctionName(closure, name).
        try setFunctionName(agent, &closure.object, PropertyKey.from(name), null);

        // 7. Return closure.
        return closure;
    }
}

/// 15.9.4 Runtime Semantics: InstantiateAsyncArrowFunctionExpression
/// https://tc39.es/ecma262/#sec-runtime-semantics-instantiateasyncarrowfunctionexpression
pub fn instantiateAsyncArrowFunctionExpression(
    agent: *Agent,
    async_arrow_function: ast.AsyncArrowFunction,
    default_name: ?[]const u8,
    source: []const u8,
) std.mem.Allocator.Error!*builtins.ECMAScriptFunction {
    const realm = agent.currentRealm();

    // 1. If name is not present, set name to the empty String.
    const name: *const String = if (default_name) |name|
        try String.fromUtf8(agent, name)
    else
        .empty;

    // 2. Let env be the LexicalEnvironment of the running execution context.
    const env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

    // 3. Let privateEnv be the running execution context's PrivateEnvironment.
    const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

    // 4. Let sourceText be the source text matched by AsyncArrowFunction.
    const source_text: SourceText = .{ .slice = .{
        .source = source,
        .source_range = async_arrow_function.source_range,
    } };

    // 5. Let head be the AsyncArrowHead that is covered by CoverCallExpressionAndAsyncArrowHead.
    // 6. Let parameters be the ArrowFormalParameters of head.
    const parameters = async_arrow_function.formal_parameters;

    // 7. Let closure be OrdinaryFunctionCreate(%AsyncFunction.prototype%, sourceText, parameters,
    //    AsyncConciseBody, lexical-this, env, privateEnv).
    const closure = try ordinaryFunctionCreate(
        agent,
        try realm.intrinsic(.async_function_prototype),
        source_text,
        parameters,
        async_arrow_function.function_body,
        .lexical_this,
        env,
        private_env,
    );

    // 8. Perform SetFunctionName(closure, name).
    try setFunctionName(agent, &closure.object, PropertyKey.from(name), null);

    // 9. Return closure.
    return closure;
}
