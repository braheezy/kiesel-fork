/// 13.2.8.4 GetTemplateObject ( templateLiteral )
/// https://tc39.es/ecma262/#sec-gettemplateobject
pub fn getTemplateObject(
    agent: *Agent,
    cache_key: u64,
    raw: *builtins.Array,
    cooked: *builtins.Array,
) std.mem.Allocator.Error!*builtins.Array {
    // 1. Let realm be the current Realm Record.
    const realm = agent.currentRealm();

    // 2. Let templateRegistry be realm.[[TemplateMap]].
    // 3. For each element element of templateRegistry, do
    if (realm.template_map.get(cache_key)) |template| {
        // a. If element.[[Site]] is the same Parse Node as templateLiteral, then
        //     i. Return element.[[Array]].
        return template;
    }

    const template = cooked;

    // 4. Let rawStrings be the TemplateStrings of templateLiteral with argument raw.
    // 5. Assert: rawStrings is a List of Strings.
    // 6. Let cookedStrings be the TemplateStrings of templateLiteral with argument cooked.
    // 7. Let count be the number of elements in the List cookedStrings.
    // 8. Assert: count ≤ 2**32 - 1.
    // 9. Let template be ! ArrayCreate(count).
    // 10. Let rawObj be ! ArrayCreate(count).
    // 11. Let index be 0.
    // 12. Repeat, while index < count,
    //     a. Let propertyKey be ! ToString(𝔽(index)).
    //     b. Let cookedValue be cookedStrings[index].
    //     c. Perform ! DefinePropertyOrThrow(template, propertyKey, PropertyDescriptor {
    //        [[Value]]: cookedValue, [[Writable]]: false, [[Enumerable]]: true,
    //        [[Configurable]]: false }).
    //     d. Let rawValue be the String value rawStrings[index].
    //     e. Perform ! DefinePropertyOrThrow(rawObj, propertyKey, PropertyDescriptor {
    //        [[Value]]: rawValue, [[Writable]]: false, [[Enumerable]]: true,
    //        [[Configurable]]: false }).
    //     f. Set index to index + 1.
    // NOTE: This is handled via the generated bytecode.

    // 13. Perform ! SetIntegrityLevel(rawObj, frozen).
    _ = raw.object.setIntegrityLevel(agent, .frozen) catch |err| try noexcept(err);

    // 14. Perform ! DefinePropertyOrThrow(template, "raw", PropertyDescriptor { [[Value]]: rawObj,
    //     [[Writable]]: false, [[Enumerable]]: false, [[Configurable]]: false }).
    try template.object.definePropertyDirect(agent, PropertyKey.from("raw"), .{
        .value_or_accessor = .{
            .value = Value.from(&raw.object),
        },
        .attributes = .none,
    });

    // 15. Perform ! SetIntegrityLevel(template, frozen).
    _ = template.object.setIntegrityLevel(agent, .frozen) catch |err| try noexcept(err);

    // 16. Append the Record { [[Site]]: templateLiteral, [[Array]]: template } to
    //     realm.[[TemplateMap]].
    try realm.template_map.putNoClobber(agent.gc_allocator, cache_key, template);

    // 17. Return template.
    return template;
}

/// 13.3.5.1.1 EvaluateNew ( constructExpr, argumentsNode )
/// https://tc39.es/ecma262/#sec-evaluatenew
pub fn evaluateNew(agent: *Agent, ctor: Value, arguments: []const Value) Agent.Error!*Object {
    // 1. Let ref be ? Evaluation of constructExpr.
    // 2. Let ctor be ? GetValue(ref).
    // 3. If argumentsNode is empty, then
    //     a. Let argList be a new empty List.
    // 4. Else,
    //     a. Let argList be ? ArgumentListEvaluation of argumentsNode.
    // NOTE: This is part of the generated bytecode.

    // 5. If IsConstructor(ctor) is false, throw a TypeError exception.
    if (!ctor.isConstructor()) {
        return agent.throwException(.type_error, "{f} is not a constructor", .{ctor});
    }

    // 6. Return ? Construct(ctor, argList).
    return ctor.asObject().construct(agent, arguments, null);
}

/// 13.3.6.2 EvaluateCall ( func, thisValueRef, argumentListNode, tailPosition )
/// https://tc39.es/ecma262/#sec-evaluatecall
pub fn evaluateCall(
    agent: *Agent,
    func: Value,
    this_value: Value,
    arg_list: []const Value,
) Agent.Error!Value {
    // 1-2.
    // NOTE: These are done in the function above, which is called by the prepare_call instruction.

    // 3. Let argList be ? ArgumentListEvaluation of argumentListNode.
    // NOTE: This is part of the generated bytecode.

    // 4. If func is not an Object, throw a TypeError exception.
    if (!func.isObject()) {
        return agent.throwException(.type_error, "{f} is not an Object", .{func});
    }

    // 5. If IsCallable(func) is false, throw a TypeError exception.
    if (!func.isCallable()) {
        return agent.throwException(.type_error, "{f} is not callable", .{func});
