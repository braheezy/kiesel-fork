/// 15.4.4 Runtime Semantics: DefineMethod
/// https://tc39.es/ecma262/#sec-runtime-semantics-definemethod
fn defineMethod(
    agent: *Agent,
    function_expression: ast.FunctionExpression,
    property_name: Value,
    obj: *Object,
    maybe_proto: ?*Object,
    source: []const u8,
) Agent.Error!(struct { key: PropertyKeyOrPrivateName, closure: *builtins.ECMAScriptFunction }) {
    const realm = agent.currentRealm();

    // 1. Let propertyKey be ? Evaluation of ClassElementName.
    const property_key: PropertyKeyOrPrivateName = if (property_name.toPrivateName()) |private_name|
        .{ .private_name = private_name }
    else if (property_name.toPropertyKey(agent)) |property_key|
        .{ .property_key = property_key }
    else |err|
        return err;

    // 2. Let envRecord be the running execution context's LexicalEnvironment.
    const env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

    // 3. Let privateEnv be the running execution context's PrivateEnvironment.
    const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

    // 4. If proto is not present, set proto to %Function.prototype%.
    const proto = maybe_proto orelse try realm.intrinsic(.function_prototype);

    // 5. Let sourceText be the source text matched by MethodDefinition.
    const source_text: SourceText = .{ .slice = .{
        .source = source,
        .source_range = function_expression.source_range,
    } };

    // 6. Let closure be OrdinaryFunctionCreate(proto, sourceText, UniqueFormalParameters,
    //    FunctionBody, non-lexical-this, envRecord, privateEnv).
    const closure = try ordinaryFunctionCreate(
        agent,
        proto,
        source_text,
        function_expression.formal_parameters,
        function_expression.function_body,
        .non_lexical_this,
        env,
        private_env,
    );

    // 7. Perform MakeMethod(closure, obj).
    makeMethod(closure, obj);

    // 8. Return the Record { [[Key]]: propertyKey, [[Closure]]: closure }.
    return .{ .key = property_key, .closure = closure };
}

/// 15.4.5 Runtime Semantics: MethodDefinitionEvaluation
/// https://tc39.es/ecma262/#sec-runtime-semantics-methoddefinitionevaluation
pub fn methodDefinitionEvaluation(
    agent: *Agent,
    // Like ast.MethodDefinition but with an evaluated ast.PropertyName
    method_definition: struct {
        property_name: Value,
        method: ast.MethodDefinition.Method,
    },
    obj: *Object,
    enumerable: bool,
    source: []const u8,
) Agent.Error!?PrivateMethodDefinition {
    const realm = agent.currentRealm();
    switch (method_definition.method) {
        // MethodDefinition : ClassElementName ( UniqueFormalParameters ) { FunctionBody }
        .method => |function_expression| {
            // 1. Let methodDef be ? DefineMethod of MethodDefinition with argument obj.
            const method_def = try defineMethod(
                agent,
                function_expression,
                method_definition.property_name,
                obj,
                null,
                source,
            );

            // 2. Perform SetFunctionName(methodDef.[[Closure]], methodDef.[[Key]]).
            try setFunctionName(agent, &method_def.closure.object, method_def.key, null);

            // 3. Return ? DefineMethodProperty(obj, methodDef.[[Key]], methodDef.[[Closure]],
            //    enumerable).
            return defineMethodProperty(
                agent,
                obj,
                method_def.key,
                &method_def.closure.object,
                enumerable,
            );
        },

        // MethodDefinition : get ClassElementName ( ) { FunctionBody }
        .get => |function_expression| {
            // 1. Let propertyKey be ? Evaluation of ClassElementName.
            const property_key_or_private_name: PropertyKeyOrPrivateName = if (method_definition.property_name.toPrivateName()) |private_name|
                .{ .private_name = private_name }
            else if (method_definition.property_name.toPropertyKey(agent)) |property_key|
                .{ .property_key = property_key }
            else |err|
                return err;

            // 2. Let envRecord be the running execution context's LexicalEnvironment.
            const env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

            // 3. Let privateEnv be the running execution context's PrivateEnvironment.
            const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

            // 4. Let sourceText be the source text matched by MethodDefinition.
            const source_text: SourceText = .{ .slice = .{
                .source = source,
                .source_range = function_expression.source_range,
            } };

            // 5. Let formalParamList be an instance of the production FormalParameters : [empty] .
            const formal_param_list: ast.FormalParameters = .{
                .items = &.{},
                .arguments_object_needed = false,
            };

            // 6. Let closure be OrdinaryFunctionCreate(%Function.prototype%, sourceText,
            //    formalParamList, FunctionBody, non-lexical-this, envRecord, privateEnv).
            const closure = try ordinaryFunctionCreate(
                agent,
                try realm.intrinsic(.function_prototype),
                source_text,
                formal_param_list,
                function_expression.function_body,
                .non_lexical_this,
                env,
                private_env,
            );

            // 7. Perform MakeMethod(closure, obj).
            makeMethod(closure, obj);

            // 8. Perform SetFunctionName(closure, propertyKey, "get").
            try setFunctionName(agent, &closure.object, property_key_or_private_name, "get");

            switch (property_key_or_private_name) {
                // 9. If propertyKey is a Private Name, then
                .private_name => |private_name| {
                    // a. Return PrivateElement { [[Key]]: propertyKey, [[Kind]]: accessor,
                    //    [[Getter]]: closure, [[Setter]]: undefined }.
                    const private_element: PrivateElement = .{
                        .accessor = .{ .getter = &closure.object, .setter = null },
                    };
                    return .{ .private_name = private_name, .private_element = private_element };
                },
                .property_key => |property_key| {
                    // 10. Let propertyDesc be the PropertyDescriptor { [[Getter]]: closure,
                    //     [[Enumerable]]: enumerable, [[Configurable]]: true }.
                    const property_desc: PropertyDescriptor = .{
                        .getter = &closure.object,
                        .enumerable = enumerable,
                        .configurable = true,
                    };

                    // 11. Perform ? DefinePropertyOrThrow(obj, propertyKey, propertyDesc).
                    try obj.definePropertyOrThrow(agent, property_key, property_desc);

                    // 12. Return empty.
                    return null;
                },
            }
        },

        // MethodDefinition : set ClassElementName ( PropertySetParameterList ) { FunctionBody }
        .set => |function_expression| {
            // 1. Let propertyKey be ? Evaluation of ClassElementName.
            const property_key_or_private_name: PropertyKeyOrPrivateName = if (method_definition.property_name.toPrivateName()) |private_name|
                .{ .private_name = private_name }
            else if (method_definition.property_name.toPropertyKey(agent)) |property_key|
                .{ .property_key = property_key }
            else |err|
                return err;

            // 2. Let envRecord be the running execution context's LexicalEnvironment.
            const env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

            // 3. Let privateEnv be the running execution context's PrivateEnvironment.
            const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

            // 4. Let sourceText be the source text matched by MethodDefinition.
            const source_text: SourceText = .{ .slice = .{
                .source = source,
                .source_range = function_expression.source_range,
            } };

            // 5. Let closure be OrdinaryFunctionCreate(%Function.prototype%, sourceText,
            //    PropertySetParameterList, FunctionBody, non-lexical-this, envRecord, privateEnv).
            const closure = try ordinaryFunctionCreate(
                agent,
                try realm.intrinsic(.function_prototype),
                source_text,
                function_expression.formal_parameters,
                function_expression.function_body,
                .non_lexical_this,
                env,
                private_env,
            );

            // 6. Perform MakeMethod(closure, obj).
            makeMethod(closure, obj);

            // 7. Perform SetFunctionName(closure, propertyKey, "set").
            try setFunctionName(agent, &closure.object, property_key_or_private_name, "set");

            switch (property_key_or_private_name) {
                // 8. If propertyKey is a Private Name, then
                .private_name => |private_name| {
                    // a. Return PrivateElement { [[Key]]: propertyKey, [[Kind]]: accessor,
                    //    [[Getter]]: undefined, [[Setter]]: closure }.
                    const private_element: PrivateElement = .{
                        .accessor = .{ .getter = null, .setter = &closure.object },
                    };
                    return .{ .private_name = private_name, .private_element = private_element };
                },
                .property_key => |property_key| {
                    // 9. Let propertyDesc be the PropertyDescriptor { [[Setter]]: closure,
                    //    [[Enumerable]]: enumerable, [[Configurable]]: true }.
                    const property_desc: PropertyDescriptor = .{
                        .setter = &closure.object,
                        .enumerable = enumerable,
                        .configurable = true,
                    };

                    // 10. Perform ? DefinePropertyOrThrow(obj, propertyKey, propertyDesc).
