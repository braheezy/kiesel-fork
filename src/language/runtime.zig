            const env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

            // 3. Let privateEnv be the running execution context's PrivateEnvironment.
            const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

            // 4. Let sourceText be the source text matched by GeneratorMethod.
            const source_text: SourceText = .{ .slice = .{
                .source = source,
                .source_range = generator_expression.source_range,
            } };

            // 5. Let closure be OrdinaryFunctionCreate(%GeneratorFunction.prototype%, sourceText,
            //    UniqueFormalParameters, GeneratorBody, non-lexical-this, envRecord, privateEnv).
            const closure = try ordinaryFunctionCreate(
                agent,
                try realm.intrinsic(.generator_function_prototype),
                source_text,
                generator_expression.formal_parameters,
                generator_expression.function_body,
                .non_lexical_this,
                env,
                private_env,
            );

            // 6. Perform MakeMethod(closure, obj).
            makeMethod(closure, obj);

            // 7. Perform SetFunctionName(closure, propertyKey).
            try setFunctionName(agent, &closure.object, property_key_or_private_name, null);

            // 8. Let proto be OrdinaryObjectCreate(%GeneratorPrototype%).
            const proto = try ordinaryObjectCreate(
