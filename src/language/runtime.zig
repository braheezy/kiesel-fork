    // 6. If tailPosition is true, perform PrepareForTailCall().
    // 7. Return ? Call(func, thisValue, argList).
    return func.asObject().call(agent, this_value, arg_list);
}

/// 13.3.7.1 Runtime Semantics: Evaluation
/// https://tc39.es/ecma262/#sec-super-keyword-runtime-semantics-evaluation
pub fn evaluateSuperCall(agent: *Agent, arg_list: []const Value) Agent.Error!Value {
    // SuperCall : super Arguments
    // 1. Let newTarget be GetNewTarget().
    const new_target = agent.getNewTarget();

    // 2. Assert: newTarget is a constructor.
    std.debug.assert(new_target.?.internalMethods().construct != null);

    // 3. Let superCtor be GetSuperConstructor().
    const super_ctor = try getSuperConstructor(agent);
    const super_ctor_value: Value = if (super_ctor) |f| Value.from(f) else .null;

    // 4. Let argList be ? ArgumentListEvaluation of Arguments.

    // 5. If IsConstructor(superCtor) is false, throw a TypeError exception.
    if (!super_ctor_value.isConstructor()) {
        return agent.throwException(
            .type_error,
            "{f} is not a constructor",
            .{super_ctor_value},
        );
    }

    // 6. Let result be ? Construct(superCtor, argList, newTarget).
    const result = try super_ctor.?.construct(agent, arg_list, new_target);

    // 7. Let thisER be GetThisEnvironment().
    const this_environment = agent.getThisEnvironment();

    // 8. Assert: thisER is a Function Environment Record.
    // 9. Perform ? BindThisValue(thisER, result).
    try this_environment.function_environment.bindThisValue(agent, Value.from(result));

    // 10. Let funcObj be thisER.[[FunctionObject]].
    // 11. Assert: funcObj is an ECMAScript function object.
    const func_obj = &this_environment.function_environment.function_object.object;

    // 12. Perform ? InitializeInstanceElements(result, funcObj).
    try result.initializeInstanceElements(agent, func_obj);

    // 13. Return result.
    return Value.from(result);
}

/// 13.3.7.2 GetSuperConstructor ( )
/// https://tc39.es/ecma262/#sec-getsuperconstructor
pub fn getSuperConstructor(agent: *Agent) std.mem.Allocator.Error!?*Object {
    // 1. Let envRecord be GetThisEnvironment().
    const env = agent.getThisEnvironment();

    // 2. Assert: envRecord is a Function Environment Record.
    std.debug.assert(env == .function_environment);

    // 3. Let activeFunc be envRecord.[[FunctionObject]].
    // 4. Assert: activeFunc is an ECMAScript function object.
    const active_func = &env.function_environment.function_object.object;

    // 5. Let superCtor be ! activeFunc.[[GetPrototypeOf]]().
    const super_ctor = active_func.internalMethods().getPrototypeOf(
        agent,
        active_func,
    ) catch |err| try noexcept(err);

    // 6. Return superCtor.
    return super_ctor;
}

/// 13.3.10.2 EvaluateImportCall ( specifierExpr [ , optionsExpr ] )
/// https://tc39.es/ecma262/#sec-evaluate-import-call
pub fn evaluateImportCall(agent: *Agent, specifier: Value, options: Value) Agent.Error!Value {
    const realm = agent.currentRealm();

    // 1. Let referrer be GetActiveScriptOrModule().
    // 2. If referrer is null, set referrer to the current Realm Record.
    const referrer: ImportedModuleReferrer = if (agent.getActiveScriptOrModule()) |script_or_module|
        switch (script_or_module) {
            .script => |script| .{ .script = script },
            .module => |module| switch (module) {
                .source_text_module => |source_text_module| .{ .module = source_text_module },
                .synthetic_module => unreachable,
            },
        }
    else
        .{ .realm = realm };

    // 3. Let specifierRef be ? Evaluation of specifierExpr.
    // 4. Let specifier be ? GetValue(specifierRef).
    // 5. If optionsExpr is present, then
    //     a. Let optionsRef be ? Evaluation of optionsExpr.
    //     b. Let options be ? GetValue(optionsRef).
    // 6. Else,
    //     a. Let options be undefined.
    // NOTE: This is part of the generated bytecode.

    // 7. Let promiseCapability be ! NewPromiseCapability(%Promise%).
    const promise_capability = newPromiseCapability(
        agent,
        Value.from(try realm.intrinsic(.promise)),
    ) catch |err| try noexcept(err);

    // 8. Let specifierString be Completion(ToString(specifier)).
    const specifier_string = specifier.toString(agent) catch |err| {
        // 9. IfAbruptRejectPromise(specifierString, promiseCapability).
        return Value.from(try promise_capability.rejectPromise(agent, err));
    };

    // 10. Let attrs be a new empty List.
    var attrs: std.ArrayList(ImportAttribute) = .empty;

    // 11. If options is not undefined, then
    if (!options.isUndefined()) {
        // a. If options is not an Object, then
        if (!options.isObject()) {
            const @"error" = try agent.createErrorObject(
                .type_error,
                "Options value is not an object",
                .{},
            );

            // i. Perform ! Call(promiseCapability.[[Reject]], undefined, « a newly created
            //    TypeError object »).
            _ = promise_capability.reject.call(
                agent,
                .undefined,
                &.{Value.from(&@"error".object)},
            ) catch |err| try noexcept(err);

            // ii. Return promiseCapability.[[Promise]].
            return Value.from(promise_capability.promise);
        }

        // b. Let attrsObj be Completion(Get(options, "with")).
        const attrs_obj = options.asObject().get(agent, PropertyKey.from("with")) catch |err| {
            // c. IfAbruptRejectPromise(attrsObj, promiseCapability).
            return Value.from(try promise_capability.rejectPromise(agent, err));
        };

        // d. If attrsObj is not undefined, then
        if (!attrs_obj.isUndefined()) {
            // i. If attrsObj is not an Object, then
            if (!attrs_obj.isObject()) {
                const @"error" = try agent.createErrorObject(
                    .type_error,
                    "'with' property is not an object",
                    .{},
                );

                // 1. Perform ! Call(promiseCapability.[[Reject]], undefined, « a newly created
                //    TypeError object »).
                _ = promise_capability.reject.call(
                    agent,
                    .undefined,
                    &.{Value.from(&@"error".object)},
                ) catch |err| try noexcept(err);

                // 2. Return promiseCapability.[[Promise]].
                return Value.from(promise_capability.promise);
            }

            // ii. Let entries be Completion(EnumerableOwnProperties(attrsObj, key+value)).
            var entries = attrs_obj.asObject().enumerableOwnProperties(
                agent,
                .key_value,
            ) catch |err| {
                // iii. IfAbruptRejectPromise(entries, promiseCapability).
                return Value.from(try promise_capability.rejectPromise(agent, err));
            };
            defer entries.deinit(agent.gc_allocator);

            // iv. For each element entry of entries, do
            for (entries.items) |entry| {
                // 1. Let key be ! Get(entry, "0").
                const key = entry.get(agent, PropertyKey.from(0)) catch |err| try noexcept(err);

                // 2. Let value be ! Get(entry, "1").
                const value = entry.get(agent, PropertyKey.from(1)) catch |err| try noexcept(err);

                // 3. If key is a String, then
                if (key.isString()) {
                    // a. If value is not a String, then
                    if (!value.isString()) {
                        const @"error" = try agent.createErrorObject(
                            .type_error,
                            "Import attribute '{f}' value is not a string",
                            .{key.asString().fmtEscaped()},
                        );

                        // i. Perform ! Call(promiseCapability.[[Reject]], undefined, « a newly
                        //    created TypeError object »).
                        _ = promise_capability.reject.call(
                            agent,
                            .undefined,
                            &.{Value.from(&@"error".object)},
                        ) catch |err| try noexcept(err);

                        // ii. Return promiseCapability.[[Promise]].
                        return Value.from(promise_capability.promise);
                    }

                    // b. Append the ImportAttribute Record { [[Key]]: key, [[Value]]: value } to
                    //    attrs.
                    try attrs.append(agent.gc_allocator, .{
                        .key = key.asString(),
                        .value = value.asString(),
                    });
                }
            }
        }

        // e. If AllImportAttributesSupported(attrs) is false, then
        if (try allImportAttributesSupported(agent, attrs.items)) |unsupported| {
            const @"error" = try agent.createErrorObject(
                .type_error,
                "Import attribute '{f}' is not supported",
                .{unsupported.fmtEscaped()},
            );

            // i. Perform ! Call(promiseCapability.[[Reject]], undefined, « a newly created
            //    TypeError object »).
            _ = promise_capability.reject.call(
                agent,
                .undefined,
                &.{Value.from(&@"error".object)},
            ) catch |err| try noexcept(err);

            // ii. Return promiseCapability.[[Promise]].
            return Value.from(promise_capability.promise);
        }

        // f. Sort attrs according to the lexicographic order of their [[Key]] field, treating the
        //    value of each such field as a sequence of UTF-16 code unit values. NOTE: This sorting
        //    is observable only in that hosts are prohibited from changing behaviour based on the
        //    order in which attributes are enumerated.
    }

    // 12. Let moduleRequest be a new ModuleRequest Record { [[Specifier]]: specifierString,
    //     [[Attributes]]: attrs }.
    const module_request: ModuleRequest = .{
        .specifier = specifier_string,
        .attributes = try attrs.toOwnedSlice(agent.gc_allocator),
    };

    // 13. Perform HostLoadImportedModule(referrer, moduleRequest, empty, promiseCapability).
    try agent.host_hooks.hostLoadImportedModule(
        agent,
        referrer,
        module_request,
        null,
        .{ .promise_capability = promise_capability },
    );

    // 14. Return promiseCapability.[[Promise]].
    return Value.from(promise_capability.promise);
}

/// 13.3.12.1 Runtime Semantics: Evaluation
/// https://tc39.es/ecma262/#sec-meta-properties-runtime-semantics-evaluation
pub fn evaluateImportMeta(agent: *Agent) std.mem.Allocator.Error!Value {
    // 1. Let module be GetActiveScriptOrModule().
    // 2. Assert: module is a Source Text Module Record.
    var module = agent.getActiveScriptOrModule().?.module.source_text_module;

    // 3. Let importMeta be module.[[ImportMeta]].
    // 4. If importMeta is empty, then
    const import_meta = module.import_meta orelse blk: {
        // a. Set importMeta to OrdinaryObjectCreate(null).
        const import_meta = try ordinaryObjectCreate(agent, null);

        // b. Let importMetaValues be HostGetImportMetaProperties(module).
        var import_meta_values = try agent.host_hooks.hostGetImportMetaProperties(agent, module);
        defer import_meta_values.deinit(agent.gc_allocator);

        // c. For each Record { [[Key]], [[Value]] } p of importMetaValues, do
        var it = import_meta_values.iterator();
        while (it.next()) |entry| {
            // i. Perform ! CreateDataPropertyOrThrow(importMeta, p.[[Key]], p.[[Value]]).
            try import_meta.createDataPropertyDirect(agent, entry.key_ptr.*, entry.value_ptr.*);
        }

        // d. Perform HostFinalizeImportMeta(importMeta, module).
        agent.host_hooks.hostFinalizeImportMeta(import_meta, module);

        // e. Set module.[[ImportMeta]] to importMeta.
        module.import_meta = import_meta;

        // f. Return importMeta.
        break :blk import_meta;
    };

    // 5. Assert: importMeta is an Object.
    // 6. Return importMeta.
    return Value.from(import_meta);
}

/// CallExpression : CoverCallExpressionAndAsyncArrowHead
/// Step 6.a.
pub fn directEval(agent: *Agent, arguments: []const Value, strict: bool) Agent.Error!Value {
    // i. Let argList be ? ArgumentListEvaluation of arguments.
    // NOTE: This is part of the generated bytecode.

    // ii. If argList has no elements, return undefined.
    if (arguments.len == 0) return .undefined;

    // iii. Let evalArg be the first element of argList.
    const eval_arg = arguments[0];

    // iv. If IsStrict(this CallExpression) is true, let strictCaller be true; else let
    //     strictCaller be false.
    const strict_caller = strict;

    // v. Return ? PerformEval(evalArg, strictCaller, true).
    return performEval(agent, eval_arg, strict_caller, true);
}

/// 13.15.3 ApplyStringOrNumericBinaryOperator ( leftValue, opText, rightValue )
/// https://tc39.es/ecma262/#sec-applystringornumericbinaryoperator
pub fn applyStringOrNumericBinaryOperator(
    agent: *Agent,
    left_value: Value,
    comptime operator: ast.BinaryExpression.Operator,
    right_value: Value,
) Agent.Error!Value {
    var final_left_value = left_value;
    var final_right_value = right_value;

    // 1. If opText is `+`, then
    if (operator == .@"+") {
        // a. Let leftPrimitive be ? ToPrimitive(leftValue).
        const left_primitive = try left_value.toPrimitive(agent, null);

        // b. Let rightPrimitive be ? ToPrimitive(rightValue).
        const right_primitive = try right_value.toPrimitive(agent, null);

        // c. If leftPrimitive is a String or rightPrimitive is a String, then
        if (left_primitive.isString() or right_primitive.isString()) {
            // i. Let leftString be ? ToString(leftPrimitive).
            const left_string = try left_primitive.toString(agent);

            // ii. Let rightString be ? ToString(rightPrimitive).
            const right_string = try right_primitive.toString(agent);

            // iii. Return the string-concatenation of leftString and rightString.
            return Value.from(try String.concat(agent, &.{ left_string, right_string }));
        }

        // d. Set leftValue to leftPrimitive.
        final_left_value = left_primitive;

        // e. Set rightValue to rightPrimitive.
        final_right_value = right_primitive;
    }

    // 2. NOTE: At this point, it must be a numeric operation.

    // 3. Let leftNumber be ? ToNumeric(leftValue).
    const left_number = try final_left_value.toNumeric(agent);

    // 4. Let rightNumber be ? ToNumeric(rightValue).
    const right_number = try final_right_value.toNumeric(agent);

    // 5. If SameType(leftNumber, rightNumber) is false, throw a TypeError exception.
    if (!Value.Numeric.sameType(left_number, right_number)) {
        return agent.throwException(
            .type_error,
            "Left-hand side and right-hand side of numeric binary expression must have the same type",
            .{},
        );
    }

    // 6. If leftNumber is a BigInt, then
    return if (left_number == .big_int) switch (operator) {
        // a. If opText is `**`, return ? BigInt::exponentiate(leftNumber, rightNumber).
        .@"**" => Value.from(try left_number.big_int.exponentiate(agent, right_number.big_int)),

        // b. If opText is `/`, return ? BigInt::divide(leftNumber, rightNumber).
        .@"/" => Value.from(try left_number.big_int.divide(agent, right_number.big_int)),

        // c. If opText is `%`, return ? BigInt::remainder(leftNumber, rightNumber).
        .@"%" => Value.from(try left_number.big_int.remainder(agent, right_number.big_int)),

        // d. If opText is `>>>`, return ? BigInt::unsignedRightShift(leftNumber, rightNumber).
        .@">>>" => Value.from(try left_number.big_int.unsignedRightShift(agent, right_number.big_int)),

        // e. Let operation be the abstract operation associated with opText in the following table:
        .@"*" => Value.from(try left_number.big_int.multiply(agent, right_number.big_int)),
        .@"+" => Value.from(try left_number.big_int.add(agent, right_number.big_int)),
        .@"-" => Value.from(try left_number.big_int.subtract(agent, right_number.big_int)),
        .@"<<" => Value.from(try left_number.big_int.leftShift(agent, right_number.big_int)),
        .@">>" => Value.from(try left_number.big_int.signedRightShift(agent, right_number.big_int)),
        .@"&" => Value.from(try left_number.big_int.bitwiseAND(agent, right_number.big_int)),
        .@"^" => Value.from(try left_number.big_int.bitwiseXOR(agent, right_number.big_int)),
        .@"|" => Value.from(try left_number.big_int.bitwiseOR(agent, right_number.big_int)),
    }
    // 7. Else,
    else switch (operator) {
        // a. Assert: leftNumber is a Number.
        // b. Let operation be the abstract operation associated with opText in the following table:
        .@"**" => Value.from(left_number.number.exponentiate(right_number.number)),
        .@"*" => Value.from(left_number.number.multiply(right_number.number)),
        .@"/" => Value.from(left_number.number.divide(right_number.number)),
        .@"%" => Value.from(left_number.number.remainder(right_number.number)),
        .@"+" => Value.from(left_number.number.add(right_number.number)),
        .@"-" => Value.from(left_number.number.subtract(right_number.number)),
        .@"<<" => Value.from(left_number.number.leftShift(right_number.number)),
        .@">>" => Value.from(left_number.number.signedRightShift(right_number.number)),
        .@">>>" => Value.from(left_number.number.unsignedRightShift(right_number.number)),
        .@"&" => Value.from(left_number.number.bitwiseAND(right_number.number)),
        .@"^" => Value.from(left_number.number.bitwiseXOR(right_number.number)),
        .@"|" => Value.from(left_number.number.bitwiseOR(right_number.number)),
    };

    // 8. Return operation(leftNumber, rightNumber).
}

/// 15.2.4 Runtime Semantics: InstantiateOrdinaryFunctionObject
/// https://tc39.es/ecma262/#sec-runtime-semantics-instantiateordinaryfunctionobject
pub fn instantiateOrdinaryFunctionObject(
    agent: *Agent,
    function_declaration: ast.FunctionDeclaration,
    env: Environment,
    private_env: ?*PrivateEnvironment,
    source: []const u8,
) std.mem.Allocator.Error!*builtins.ECMAScriptFunction {
    // FunctionDeclaration : function ( FormalParameters ) { FunctionBody }
    // NOTE: An anonymous FunctionDeclaration can only occur as part of an export default
    // declaration, and its function code is therefore always strict mode code.
    // 1. Let sourceText be the source text matched by FunctionDeclaration.
    // 2. Let closure be OrdinaryFunctionCreate(%Function.prototype%, sourceText, FormalParameters,
    //    FunctionBody, non-lexical-this, envRecord, privateEnv).
    // 3. Perform SetFunctionName(closure, "default").
    // 4. Perform MakeConstructor(closure).
    // 5. Return closure.

    // FunctionDeclaration : function BindingIdentifier ( FormalParameters ) { FunctionBody }
    // 1. Let name be the StringValue of BindingIdentifier.
    const name = if (function_declaration.identifier) |identifier|
        try String.fromUtf8(agent, identifier)
    else
        String.fromLiteral("default");

    // 2. Let sourceText be the source text matched by FunctionDeclaration.
    const source_text: SourceText = .{ .slice = .{
        .source = source,
        .source_range = function_declaration.source_range,
    } };

    // 3. Let closure be OrdinaryFunctionCreate(%Function.prototype%, sourceText, FormalParameters,
    //    FunctionBody, non-lexical-this, envRecord, privateEnv).
    // 4. Perform SetFunctionName(closure, name).
    // 5. Perform MakeConstructor(closure).
    const closure = try ordinaryFunctionCreateFast(
        agent,
        source_text,
        function_declaration.formal_parameters,
        function_declaration.function_body,
        env,
        private_env,
        name,
    );

    // 6. Return closure.
    return closure;
}

/// 15.2.5 Runtime Semantics: InstantiateOrdinaryFunctionExpression
/// https://tc39.es/ecma262/#sec-runtime-semantics-instantiateordinaryfunctionexpression
pub fn instantiateOrdinaryFunctionExpression(
    agent: *Agent,
    function_expression: ast.FunctionExpression,
    default_name: ?[]const u8,
    source: []const u8,
) std.mem.Allocator.Error!*builtins.ECMAScriptFunction {
    // FunctionExpression : function BindingIdentifier ( FormalParameters ) { FunctionBody }
    if (function_expression.identifier) |identifier| {
        // 1. Assert: name is not present.
        std.debug.assert(default_name == null);

        // 2. Set name to the StringValue of BindingIdentifier.
        const name = try String.fromUtf8(agent, identifier);

        // 3. Let outerEnv be the running execution context's LexicalEnvironment.
        const outer_env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

        // 4. Let funcEnv be NewDeclarativeEnvironment(outerEnv).
        const func_env = try newDeclarativeEnvironment(agent.gc_allocator, outer_env);

        // 5. Perform ! funcEnv.CreateImmutableBinding(name, false).
        func_env.createImmutableBinding(agent, name, false) catch |err| try noexcept(err);

        // 6. Let privateEnv be the running execution context's PrivateEnvironment.
        const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

        // 7. Let sourceText be the source text matched by FunctionExpression.
        const source_text: SourceText = .{ .slice = .{
            .source = source,
            .source_range = function_expression.source_range,
        } };

        // 8. Let closure be OrdinaryFunctionCreate(%Function.prototype%, sourceText,
        //    FormalParameters, FunctionBody, non-lexical-this, funcEnv, privateEnv).
        // 9. Perform SetFunctionName(closure, name).
        // 10. Perform MakeConstructor(closure).
        const closure = try ordinaryFunctionCreateFast(
            agent,
            source_text,
            function_expression.formal_parameters,
            function_expression.function_body,
            .{ .declarative_environment = func_env },
            private_env,
            name,
        );

        // 11. Perform ! funcEnv.InitializeBinding(name, closure).
        func_env.initializeBinding(name, Value.from(&closure.object));

        // 12. Return closure.
        return closure;
    }
    // FunctionExpression : function ( FormalParameters ) { FunctionBody }
    else {
        // 1. If name is not present, set name to the empty String.
        const name: *const String = if (default_name) |name|
            try String.fromUtf8(agent, name)
        else
            .empty;

        // 2. Let envRecord be the LexicalEnvironment of the running execution context.
        const env = agent.runningExecutionContext().ecmascript_code.lexical_environment;

        // 3. Let privateEnv be the running execution context's PrivateEnvironment.
        const private_env = agent.runningExecutionContext().ecmascript_code.private_environment;

        // 4. Let sourceText be the source text matched by FunctionExpression.
        const source_text: SourceText = .{ .slice = .{
            .source = source,
            .source_range = function_expression.source_range,
        } };

        // 5. Let closure be OrdinaryFunctionCreate(%Function.prototype%, sourceText,
        //    FormalParameters, FunctionBody, non-lexical-this, envRecord, privateEnv).
        // 6. Perform SetFunctionName(closure, name).
        // 7. Perform MakeConstructor(closure).
        const closure = try ordinaryFunctionCreateFast(
            agent,
            source_text,
            function_expression.formal_parameters,
            function_expression.function_body,
            env,
            private_env,
            name,
        );

        // 8. Return closure.
        return closure;
    }
}

