pub const YieldStarResult = union(enum) {
    yield,
    done: Value,
    @"return": Value,
};

/// 15.5.5 Runtime Semantics: Evaluation
/// https://tc39.es/ecma262/#sec-generator-function-definitions-runtime-semantics-evaluation
pub fn evaluateYieldStar(
    agent: *Agent,
    iterator: *Iterator,
    received: builtins.generator.Completion,
) Agent.Error!YieldStarResult {
    // YieldExpression : yield * AssignmentExpression

    // 1. Let genKind be GetGeneratorKind().
    const gen_kind = getGeneratorKind(agent);

    // 2. Assert: genKind is either sync or async.
    std.debug.assert(gen_kind == .sync or gen_kind == .async);

    // 3. Let exprRef be ? Evaluation of AssignmentExpression.
    // 4. Let value be ? GetValue(exprRef).
    // 5. Let iteratorRecord be ? GetIterator(value, genKind).
    // 6. Let iterator be iteratorRecord.[[Iterator]].
    // 7. Let received be NormalCompletion(undefined).
    // NOTE: Steps 3-7 are handled via the generated bytecode.

    // 8. Repeat,
    switch (received) {
        // a. If received is a normal completion, then
        .normal => |value| {
            // i. Let innerResult be ? Call(iteratorRecord.[[NextMethod]],
            //    iteratorRecord.[[Iterator]], « received.[[Value]] »).
            var inner_result = try iterator.next_method.call(
                agent,
                Value.from(iterator.iterator),
                &.{value},
            );

            // ii. If genKind is async, set innerResult to ? Await(innerResult).
            if (gen_kind == .async) {
                inner_result = try await(agent, inner_result);
            }

            // iii. If innerResult is not an Object, throw a TypeError exception.
            if (!inner_result.isObject()) {
                return agent.throwException(.type_error, "{f} is not an Object", .{inner_result});
            }

            // iv. Let done be ? IteratorComplete(innerResult).
            const done = try Iterator.complete(agent, inner_result.asObject());

            // v. If done is true, then
            if (done) {
                // 1. Return ? IteratorValue(innerResult).
                return .{ .done = try Iterator.value(agent, inner_result.asObject()) };
            }

            // vi. If genKind is async, set received to Completion(AsyncGeneratorYield(
            //     ? IteratorValue(innerResult))).
            // vii. Else, set received to Completion(GeneratorYield(innerResult)).
            switch (gen_kind) {
                .async => {
                    const inner_value = try Iterator.value(agent, inner_result.asObject());
                    _ = try asyncGeneratorYield(agent, try builtins.await(agent, inner_value));
                },
                .sync => _ = try generatorYield(agent, inner_result.asObject()),
                .non_generator => unreachable,
            }
            return .yield;
        },
        // b. Else if received is a throw completion, then
        .throw => |value| {
            // i. Let throw be ? GetMethod(iterator, "throw").
            const maybe_throw = try iterator.iterator.getMethod(agent, PropertyKey.from("throw"));

            // ii. If throw is not undefined, then
            if (maybe_throw) |throw| {
                // 1. Let innerResult be ? Call(throw, iterator, « received.[[Value]] »).
                var inner_result = try throw.call(
                    agent,
                    Value.from(iterator.iterator),
                    &.{value},
                );

                // 2. If genKind is async, set innerResult to ? Await(innerResult).
                if (gen_kind == .async) {
                    inner_result = try await(agent, inner_result);
                }

                // 3. NOTE: Exceptions from the inner iterator `throw` method are propagated. Normal
                //    completions from an inner `throw` method are processed similarly to an inner
                //    `next`.

                // 4. If innerResult is not an Object, throw a TypeError exception.
                if (!inner_result.isObject()) {
                    return agent.throwException(.type_error, "{f} is not an Object", .{inner_result});
                }

                // 5. Let done be ? IteratorComplete(innerResult).
                const done = try Iterator.complete(agent, inner_result.asObject());

                // 6. If done is true, then
                if (done) {
                    // a. Return ? IteratorValue(innerResult).
                    return .{ .done = try Iterator.value(agent, inner_result.asObject()) };
                }

                // 7. If genKind is async, set received to Completion(AsyncGeneratorYield(
                //    ? IteratorValue(innerResult))).
                // 8. Else, set received to Completion(GeneratorYield(innerResult)).
                switch (gen_kind) {
                    .async => {
                        const inner_value = try Iterator.value(agent, inner_result.asObject());
                        _ = try asyncGeneratorYield(agent, try builtins.await(agent, inner_value));
                    },
                    .sync => _ = try generatorYield(agent, inner_result.asObject()),
                    .non_generator => unreachable,
                }
                return .yield;
            } else {
                // iii. Else,
                // 1. NOTE: If iterator does not have a `throw` method, this throw is going to
                //    terminate the `yield*` loop. But first we need to give iterator a chance to
                //    clean up.
                // 2. Let closeCompletion be NormalCompletion(empty).
                const close_completion: Agent.Error!void = {};

                // 3. If genKind is async, perform ? AsyncIteratorClose(iteratorRecord,
                //    closeCompletion).
                // 4. Else, perform ? IteratorClose(iteratorRecord, closeCompletion).
                switch (gen_kind) {
                    .async => _ = try iterator.closeAsync(agent, close_completion),
                    .sync => _ = try iterator.close(agent, close_completion),
                    .non_generator => unreachable,
                }

                // 5. NOTE: The next step throws a TypeError to indicate that there was a `yield*`
                //    protocol violation: iterator does not have a `throw` method.
                // 6. Throw a TypeError exception.
                return agent.throwException(
                    .type_error,
                    "Iterator does not have a 'throw' method",
                    .{},
                );
            }
        },
        // c. Else,
        .@"return" => |value| {
            // i. Assert: received is a return completion.
            // ii. Let return be ? GetMethod(iterator, "return").
            const maybe_return = try iterator.iterator.getMethod(agent, PropertyKey.from("return"));

            // iii. If return is undefined, then
            const @"return" = maybe_return orelse {
                // 1. Let receivedValue be received.[[Value]].
                var received_value = value;

                // 2. If genKind is async, then
                if (gen_kind == .async) {
                    // a. Set receivedValue to ? Await(receivedValue).
                    received_value = try await(agent, received_value);
                }

                // 3. Return ReturnCompletion(receivedValue).
                return .{ .@"return" = received_value };
            };

            // iv. Let innerReturnResult be ? Call(return, iterator, « received.[[Value]] »).
            var inner_return_result = try @"return".call(
                agent,
                Value.from(iterator.iterator),
                &.{value},
            );

            // v. If genKind is async, set innerReturnResult to ? Await(innerReturnResult).
            if (gen_kind == .async) {
                inner_return_result = try await(agent, inner_return_result);
            }

            // vi. If innerReturnResult is not an Object, throw a TypeError exception.
            if (!inner_return_result.isObject()) {
                return agent.throwException(
                    .type_error,
                    "{f} is not an Object",
                    .{inner_return_result},
                );
            }

            // vii. Let done be ? IteratorComplete(innerReturnResult).
            const done = try Iterator.complete(agent, inner_return_result.asObject());

            // viii. If done is true, then
            if (done) {
                // 1. Let returnedValue be ? IteratorValue(innerReturnResult).
                const returned_value = try Iterator.value(agent, inner_return_result.asObject());

                // 2. Return ReturnCompletion(returnedValue).
                return .{ .@"return" = returned_value };
            }

            // ix. If genKind is async, set received to Completion(AsyncGeneratorYield(
            //     ? IteratorValue(innerReturnResult))).
            // x. Else, set received to Completion(GeneratorYield(innerReturnResult)).
            switch (gen_kind) {
                .async => {
                    const inner_value = try Iterator.value(agent, inner_return_result.asObject());
                    _ = try asyncGeneratorYield(agent, try builtins.await(agent, inner_value));
                },
                .sync => _ = try generatorYield(agent, inner_return_result.asObject()),
                .non_generator => unreachable,
            }
            return .yield;
        },
    }
}

